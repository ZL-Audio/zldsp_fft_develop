// Offline MPFR generator; see README.md for formulas and references.
#include <mpfr.h>

#include <cstdio>
#include <fstream>
#include <iostream>
#include <iterator>
#include <sstream>
#include <stdexcept>
#include <string>

namespace {
    struct Split {
        double hi, lo;
    };

    std::string hex(const double value) {
        char buffer[64];
        std::snprintf(buffer, sizeof(buffer), "%a", value);
        return buffer;
    }

    std::string format(const Split value) {
        return "{" + hex(value.hi) + ", " + hex(value.lo) + "}";
    }

    // Certify both words with outward-rounded MPFR bounds.
    template <typename Evaluate>
    Split split(const Evaluate& evaluate) {
        for (mpfr_prec_t precision = 192; precision <= 3072; precision *= 2) {
            mpfr_t lower, upper;
            mpfr_inits2(precision, lower, upper, static_cast<mpfr_ptr>(nullptr));
            evaluate(lower, MPFR_RNDD);
            evaluate(upper, MPFR_RNDU);
            const double hi = mpfr_get_d(lower, MPFR_RNDN);
            const bool high_agrees = hi == mpfr_get_d(upper, MPFR_RNDN);
            mpfr_sub_d(lower, lower, hi, MPFR_RNDD);
            mpfr_sub_d(upper, upper, hi, MPFR_RNDU);
            const double lo = mpfr_get_d(lower, MPFR_RNDN);
            const bool low_agrees = lo == mpfr_get_d(upper, MPFR_RNDN);
            mpfr_clears(lower, upper, static_cast<mpfr_ptr>(nullptr));
            if (high_agrees && low_agrees) {
                return {hi == 0.0 ? 0.0 : hi, lo == 0.0 ? 0.0 : lo};
            }
        }
        throw std::runtime_error("Could not certify a constant's rounding");
    }

    Split root(const unsigned index, const bool sine) {
        return split([&](mpfr_ptr value, const mpfr_rnd_t rounding) {
            // Exact phase: x = 2*j/1024.
            mpfr_set_ui_2exp(value, index, -9, MPFR_RNDN);
            if (sine) {
                mpfr_sinpi(value, value, rounding);
            } else {
                mpfr_cospi(value, value, rounding);
            }
        });
    }

    Split coefficient(const unsigned factorial, const bool negative) {
        return split([&](mpfr_ptr value, const mpfr_rnd_t rounding) {
            // Factorials through 11! are exact at this precision.
            mpfr_fac_ui(value, factorial, MPFR_RNDN);
            mpfr_si_div(value, negative ? -1 : 1, value, rounding);
        });
    }

    std::string generate() {
        std::ostringstream out;
        out << "// generated by tools/twiddle/generate.cpp; do not edit\n"
            << "// formulas and references: tools/twiddle/README.md\n"
            << "#ifndef ZLDSP_FFT_COMMON_TWIDDLE_CONSTANTS_HPP_\n"
            << "#define ZLDSP_FFT_COMMON_TWIDDLE_CONSTANTS_HPP_\n\n"
            << "namespace zldsp::fft::detail::twiddle {\n"
            << "    struct DoubleDouble { double hi, lo; };\n"
            << "    struct Anchor { DoubleDouble c, s; };\n\n"
            << "    // first-octant anchors shared by all types and SIMD targets\n"
            << "    inline constexpr Anchor kAnchors[] = {\n";
        for (unsigned j = 0; j <= 128; ++j) {
            out << "        {" << format(root(j, false)) << ", " << format(root(j, true)) << "},\n";
        }
        out << "    };\n"
            << "    static_assert(sizeof(kAnchors) == 4128);\n\n";
        const auto tau = split([](mpfr_ptr value, const mpfr_rnd_t rounding) {
            mpfr_const_pi(value, rounding);
            mpfr_mul_2ui(value, value, 1, rounding);
        });
        out << "    inline constexpr DoubleDouble kTau = " << format(tau) << ";\n"
            << "    inline constexpr double kInvSqrt2 = " << hex(root(128, false).hi) << ";\n\n"
            << "    // Taylor coefficients for sin(t)-t and cos(t)-1, |t| < 2*pi/1024\n"
            << "    inline constexpr DoubleDouble kSinResidual[] = {\n";
        for (unsigned j = 1; j <= 5; ++j) {
            out << "        " << format(coefficient(2 * j + 1, (j & 1) != 0)) << ",\n";
        }
        out << "    };\n"
            << "    inline constexpr DoubleDouble kCosResidual[] = {\n";
        for (unsigned j = 1; j <= 5; ++j) {
            out << "        " << format(coefficient(2 * j, (j & 1) != 0)) << ",\n";
        }
        out << "    };\n}\n\n#endif\n";
        return out.str();
    }
}

int main(const int argc, const char* const argv[]) {
    try {
        const auto generated = generate();
        if (argc == 1) {
            std::cout << generated;
        } else if (argc == 3 && std::string(argv[1]) == "--check") {
            std::ifstream input(argv[2], std::ios::binary);
            const std::string actual{std::istreambuf_iterator<char>(input), std::istreambuf_iterator<char>()};
            if (!input || actual != generated) {
                std::cerr << "Generated constants differ from " << argv[2] << '\n';
                return 1;
            }
            std::cout << "Generated constants match " << argv[2] << '\n';
        } else {
            std::cerr << "usage: generate_twiddle_constants [--check header]\n";
            return 2;
        }
    } catch (const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
